/** Traduce el texto visible de una opción, nunca el valor que se guarda. */
export function optionLabel(value: string, path?: readonly (string | number)[]): string {
  const key = [...(path ?? [])].reverse().find((part): part is string => typeof part === "string")
  const contextual = key ? CONTEXT_LABELS[key]?.[value] : undefined
  if (contextual) return contextual
  const direct = VALUE_LABELS[value]
  if (direct) return direct
  return value
    .replace(/[_-]+/g, " ")
    .replace(/^./, (c) => c.toUpperCase())
}

