function humaniseEs(key: string): string {
  const words = key
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean)
  if (words.length === 0) return key
  // En inglés el sustantivo va al final; en español, al principio.
  const translated = words.map((word) => TOKENS[word] ?? word).reverse()
  const text = translated.join(" ")
  return text.charAt(0).toUpperCase() + text.slice(1)
}

/** Etiqueta visible de un campo del schema. */
export function fieldLabel(key: string): string {
  return FIELD_LABELS[key] ?? humaniseEs(key)
}
